/* ── Engine ─────────────────────────────────────────────────────────────── */

let currentLang = localStorage.getItem('sdcLang') || 'BM';

function t(key) {
  const lang = T[currentLang] || T.BM;
  return lang[key] || T.BM[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('sdcLang', lang);

  const map = T[lang] || T.BM;

  /* Plain text */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = map[el.dataset.i18n] || T.BM[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });

  /* HTML content */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = map[el.dataset.i18nHtml] || T.BM[el.dataset.i18nHtml];
    if (v !== undefined) el.innerHTML = v;
  });

  /* Placeholder */
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = map[el.dataset.i18nPh] || T.BM[el.dataset.i18nPh];
    if (v !== undefined) el.placeholder = v;
  });

  /* Active lang btn */
  document.querySelectorAll('.lang-btn').forEach(b => {
    const bl = b.dataset.lang;
    b.classList.toggle('active', bl === lang);
  });

  /* html lang attr */
  document.documentElement.lang = { BM:'ms', EN:'en', ZH:'zh', IB:'iba' }[lang] || 'ms';
}

function initLang() {
  setLang(currentLang);
}
